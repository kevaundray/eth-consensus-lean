#!/usr/bin/env python3
"""sectionS_removed.py — per-entry evidence for §S entries removed because their declarations lost
their stock marker (the `reach_outage.py --check-section-s` criterion).

    python3 tools/sectionS_removed.py --repo STORE --base BASE --head HEAD \
        --old-list OLD.md --new-list tools/sectionS.md [--compare REV] > tools/sectionS-removed.md

For each entry of OLD.md that is not in NEW.md, prints its header at BASE (with its marker) and at
HEAD (without), grouped by the first commit of BASE..HEAD (first parent) whose header has no marker.
Exits 1 unless the removed entries are exactly the OLD.md entries that have a marker at BASE and none
at HEAD (entries naming a declaration absent at either revision are not compared). With --compare
REV, reports on stderr each removed entry whose HEAD header differs from its header at REV.
"""
import argparse, difflib, os, re, subprocess, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import reach_outage as ro


def entries(path):
    out = []
    for l in open(path):
        m = re.match(r"- `([^`]+)`\s*[—-]+\s*(\S+\.lean):\d+", l)
        if m:
            out.append((m.group(1), m.group(2)))
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    for f in ("--repo", "--base", "--head", "--old-list", "--new-list"):
        ap.add_argument(f, required=True)
    ap.add_argument("--compare")
    a = ap.parse_args()
    git = lambda *x: subprocess.run(["git", "-C", a.repo, *x], capture_output=True, text=True).stdout
    base, head = git("rev-parse", a.base).strip(), git("rev-parse", a.head).strip()
    cache = {}

    def at(rev, name, path):
        """(line, header, marker) of the unique declaration `name` in `path` at `rev`, or None."""
        if (rev, path) not in cache:
            t = git("show", f"{rev}:{path}")
            L = t.split("\n")
            cache[(rev, path)] = (L, [(i, ro.DECL.match(l).group(1)) for i, l in enumerate(L) if ro.DECL.match(l)],
                                  ro.s_scope(t))
        L, idx, scope = cache[(rev, path)]
        hits = [k for k, (_, n) in enumerate(idx) if n.split(".")[-1] == name.split(".")[-1]]
        if len(hits) != 1:
            return None
        i = idx[hits[0]][0]
        j = idx[hits[0] + 1][0] if hits[0] + 1 < len(idx) else len(L)
        decl = "\n".join(L[i:j])
        return i + 1, ro.header(decl), ro.stock_marker(decl, scope[i])

    old, new = entries(a.old_list), set(entries(a.new_list))
    removed = [e for e in old if e not in new]
    lost = []
    for e in old:
        b, h = at(base, *e), at(head, *e)
        if b and h and b[2] and not h[2]:
            lost.append(e)
    if set(removed) != set(lost):
        print(f"removed but not marker-lost: {sorted(set(removed) - set(lost))}", file=sys.stderr)
        print(f"marker-lost but not removed: {sorted(set(lost) - set(removed))}", file=sys.stderr)
        return 1

    chain = git("rev-list", "--first-parent", "--reverse", f"{base}..{head}").split()
    groups = {}
    for e in removed:
        first = next(c for c in chain if not (at(c, *e) or (0, "", None))[2])
        groups.setdefault(first, []).append(e)

    print(f"# §S entries removed: stock marker at `{base[:8]}`, none at `{head[:8]}`\n")
    print(f"{len(removed)} entries, grouped by the first commit of `{base[:8]}..{head[:8]}` (first parent) "
          "whose header has no stock marker. A marker is `hstock`, `committeeSize =`, `⟨S, stock⟩`, or `S` "
          "bound to `Setup` by a header binder or by the `variable` in scope (`reach_outage.py "
          "--check-section-s`). Headers end at the first `:=` outside brackets; comments are stripped. "
          "Generated by `tools/sectionS_removed.py`.\n")
    for c in chain:
        if c not in groups:
            continue
        print(f"## `{c[:8]}` {git('log', '-1', '--format=%s', c).strip()} — {len(groups[c])}\n")
        for name, path in groups[c]:
            l0, h0, m0 = at(base, name, path)
            l1, h1, _ = at(head, name, path)
            print(f"### `{name}` — {path}\n")
            print(f"- `{base[:8]}`:{l0}: marker `{m0}`.")
            print(f"- `{head[:8]}`:{l1}: no marker.\n")
            print("Header, `-` only at the base, `+` only at the head:\n")
            d = list(difflib.unified_diff(h0.split("\n"), h1.split("\n"), lineterm="", n=10**6))[3:]
            print("```diff\n" + "\n".join(d) + "\n```\n")
        print(f"{c[:8]} {len(groups[c])}", file=sys.stderr)
    if a.compare:
        cmp = git("rev-parse", a.compare).strip()
        for e in removed:
            r, h = at(cmp, *e), at(head, *e)
            if r is None or r[1] != h[1] or r[0] != h[0]:
                why = "absent" if r is None else ("header" if r[1] != h[1] else f"line {r[0]} → {h[0]}")
                print(f"vs {cmp[:8]}: {e[0]} — {e[1]}: {why}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
